package main

import "fmt"

func main() {
	// integer
	fmt.Println(1 + 8)
	fmt.Println(1)

	//string
	fmt.Println("Hello golang")

	// boolean
	fmt.Println(true)
	fmt.Println(false)

	// float
	fmt.Println(1.2 + 3.4)
	fmt.Println(1.2)

	// complex
	fmt.Println(1.2 + 3.4i)
	fmt.Println(1.2i)

	// byte
	fmt.Println('a')
	fmt.Println('A')
}
